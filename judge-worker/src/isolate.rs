use tempfile::{self, tempdir};
use zip::ZipArchive;

use crate::{
    language_config::{Command, LanguageConfig},
    problems::{Problem, testcases_from_dir},
};
use std::{
    fs::{self, File, read_to_string},
    path::{Path, PathBuf},
    process::{Command as ProcessCommand, ExitStatus},
    time::Duration,
};

pub struct IsolateBox {
    box_id: u32,
    box_dir: PathBuf,
}

// https://www.ucw.cz/isolate/isolate.1.html#_limits
#[derive(Debug, Clone, Default)]
pub struct Limits {
    pub memory_kib: Option<u64>,
    pub time: Option<Duration>,
    pub wall_time: Option<Duration>,
    pub extra_time: Option<Duration>,
    pub stack_kib: Option<u64>,
    pub open_files: Option<u32>,
    pub file_size_kib: Option<u64>,
    pub core_size_kib: Option<u64>,
    pub processes: ProcessLimit,
}

#[derive(Debug, Clone, Copy, Default)]
pub enum ProcessLimit {
    #[default]
    Default, // default process limit is 1
    Max(u32),
    Unlimited,
}

#[derive(Debug, Clone, Copy)]
pub struct DiskQuota {
    pub blocks: u64,
    pub inodes: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MetadataStatus {
    RuntimeError,
    Signal,
    Timeout,
    InternalError,
}

#[derive(Default, Debug, Clone)]
// https://www.ucw.cz/isolate/isolate.1.html#_meta_files
// Many fields are optional because they are only conditionally present in the the metadata file generated by isolate.
// cg_oom_killed and killed are binary flags either present or not, so they are represented as bools.
// For fields like time, we would expect them to be always present.
// However, we keep the field as optional when parsing and representing metadata, and we can check for its presence when we use it.
pub struct Metadata {
    cg_mem: Option<u64>,
    cg_oom_killed: bool,
    csw_forced: Option<u64>,
    csw_voluntary: Option<u64>,
    exitcode: Option<u8>,
    exitsig: Option<u8>,
    killed: bool,
    max_rss: Option<u64>,
    message: Option<String>,
    status: Option<MetadataStatus>,
    time: Option<f64>,
    time_wall: Option<f64>,
}

fn read_metadata(path: &Path) -> Result<Metadata, Box<dyn std::error::Error>> {
    let contents = read_to_string(path)?;

    let mut metadata = Metadata::default();
    for line in contents.lines() {
        let (key, value) = line
            .split_once(':')
            .ok_or("bad metadata file contents: failed to get key value pair")?;

        match key {
            "cg-mem" => metadata.cg_mem = Some(value.parse()?),
            "cg-oom-killed" => metadata.cg_oom_killed = true,
            "csw-forced" => metadata.csw_forced = Some(value.parse()?),
            "csw-voluntary" => metadata.csw_voluntary = Some(value.parse()?),
            "exitcode" => metadata.exitcode = Some(value.parse()?),
            "exitsig" => metadata.exitsig = Some(value.parse()?),
            "killed" => metadata.killed = true,
            "max-rss" => metadata.max_rss = Some(value.parse()?),
            "message" => metadata.message = Some(value.to_owned()),
            "status" => {
                metadata.status = Some(match value {
                    "RE" => MetadataStatus::RuntimeError,
                    "SG" => MetadataStatus::Signal,
                    "TO" => MetadataStatus::Timeout,
                    "XX" => MetadataStatus::InternalError,
                    _ => {
                        return Err(
                            format!("bad metadata file contents: unknown status {value}").into(),
                        );
                    }
                });
            }
            "time" => metadata.time = Some(value.parse()?),
            "time-wall" => metadata.time_wall = Some(value.parse()?),
            _ => {
                return Err(format!("bad metadata file contents: unknown key {key}").into());
            }
        }
    }

    Ok(metadata)
}

pub struct IsolateResult {
    status: ExitStatus,
    meta: Metadata,
}

impl IsolateBox {
    pub fn new(box_id: u32, quota: Option<DiskQuota>) -> Result<Self, Box<dyn std::error::Error>> {
        let mut isolate = ProcessCommand::new("isolate");
        isolate.arg(format!("--box-id={box_id}")).arg("--cg");
        if let Some(quota) = quota {
            isolate.arg(format!("--quota={},{}", quota.blocks, quota.inodes));
        }
        let output = isolate.arg("--init").output()?;

        if !output.status.success() {
            return Err(format!(
                "failed to initialize isolate box: {}",
                String::from_utf8_lossy(&output.stderr)
            )
            .into());
        }

        let root = String::from_utf8(output.stdout)?;
        let box_dir = PathBuf::from(root.trim()).join("box");

        Ok(Self { box_id, box_dir })
    }

    fn isolate(&self) -> ProcessCommand {
        let mut command = ProcessCommand::new("isolate");
        command.arg(format!("--box-id={}", self.box_id));
        command
    }

    fn expand_arg(arg: &str, substitutions: &[(&str, &str)]) -> String {
        substitutions
            .iter()
            .fold(arg.to_owned(), |expanded, (key, value)| {
                expanded.replace(key, value)
            })
    }

    fn apply_limits(command: &mut ProcessCommand, limits: &Limits) {
        if let Some(memory_kib) = limits.memory_kib {
            command.arg(format!("--cg-mem={memory_kib}"));
        }
        if let Some(time) = limits.time {
            command.arg(format!("--time={}", time.as_secs_f64()));
        }
        if let Some(wall_time) = limits.wall_time {
            command.arg(format!("--wall-time={}", wall_time.as_secs_f64()));
        }
        if let Some(extra_time) = limits.extra_time {
            command.arg(format!("--extra-time={}", extra_time.as_secs_f64()));
        }
        if let Some(stack_kib) = limits.stack_kib {
            command.arg(format!("--stack={stack_kib}"));
        }
        if let Some(open_files) = limits.open_files {
            command.arg(format!("--open-files={open_files}"));
        }
        if let Some(file_size_kib) = limits.file_size_kib {
            command.arg(format!("--fsize={file_size_kib}"));
        }
        if let Some(core_size_kib) = limits.core_size_kib {
            command.arg(format!("--core={core_size_kib}"));
        }
        match limits.processes {
            ProcessLimit::Default => {}
            ProcessLimit::Max(max) => {
                command.arg(format!("--processes={max}"));
            }
            ProcessLimit::Unlimited => {
                command.arg("--processes");
            }
        }
    }

    fn run(
        &self,
        command: &Command,
        language: &LanguageConfig,
        source: &str,
        output: &str,
        writable: bool,
        limits: &Limits,
    ) -> Result<IsolateResult, Box<dyn std::error::Error>> {
        let substitutions = [("{source}", source), ("{output}", output)];
        let box_mount = if writable {
            format!("--dir=/box={}:rw", self.box_dir.display())
        } else {
            format!("--dir=/box={}", self.box_dir.display())
        };

        let usr_mount = format!("--dir=/usr={}", language.environment.display());

        let program = Self::expand_arg(&command.program, &substitutions);

        let temp_dir = tempdir()?;
        let metadata_path = temp_dir.path().join("meta");
        println!("temp dir is {}", temp_dir.path().display());

        let mut isolate = self.isolate();
        isolate
            .arg("--no-default-dirs")
            .arg(box_mount)
            .arg("--dir=/tmp:tmp")
            .arg("--dir=/nix/store")
            .arg(usr_mount)
            .arg("--chdir=/box")
            .arg("--cg")
            .arg(format!("--meta={}", metadata_path.display()));

        Self::apply_limits(&mut isolate, limits);
        isolate.arg("--run").arg("--").arg(program);

        isolate.args(
            command
                .args
                .iter()
                .map(|arg| Self::expand_arg(arg, &substitutions)),
        );

        Ok(IsolateResult {
            status: isolate.status()?,
            meta: read_metadata(&metadata_path)?,
        })
    }

    fn copy_to_sandbox(&self, source: &Path) -> Result<String, Box<dyn std::error::Error>> {
        let source_name = source
            .file_name()
            .and_then(|name| name.to_str())
            .ok_or("invalid source filename")?;

        let sandbox_source = self.box_dir.join(source_name);

        fs::copy(source, sandbox_source)?;

        Ok(source_name.to_owned())
    }

    fn unzip_problem_package(
        &self,
        problem: &Path,
        destination: &Path,
    ) -> Result<(), Box<dyn std::error::Error>> {
        let file = File::open(problem)?;
        let mut zip = ZipArchive::new(file)?;
        zip.extract_unwrapped_root_dir(&destination, zip::read::root_dir_common_filter)?;

        let files = destination.read_dir()?;
        println!("listing extracted files:");
        for file in files {
            let file_name = (file?).file_name();
            println!("\t{file_name:?}");
        }

        Ok(())
    }

    fn get_problem_from_path(&self, problem: &Path) -> Result<Problem, Box<dyn std::error::Error>> {
        let package_dir = self.box_dir.join("package");
        self.unzip_problem_package(problem, &package_dir)?;

        let problem_dir = package_dir.join("problem");
        let metadata_path = problem_dir.join("problem.yaml");
        let sample_dir = problem_dir.join("data").join("sample");
        let secret_dir = problem_dir.join("data").join("secret");

        Ok(Problem {
            metadata: crate::problems::ProblemMetadata::from_yaml_file(metadata_path)?,
            sample_tests: testcases_from_dir(&sample_dir, "sample")?,
            secret_tests: testcases_from_dir(&secret_dir, "secret")?,
        })
    }

    pub fn run_submission(
        &self,
        language: &LanguageConfig,
        source: &str,
        problem: &Path,
    ) -> Result<Metadata, Box<dyn std::error::Error>> {
        let source_name = format!("source.{}", language.file_extension);
        let source_path = self.box_dir.join(&source_name);
        fs::write(&source_path, source)?;

        let output_name = "main";
        let compile_limits = Limits {
            time: Some(Duration::from_secs(10)),
            wall_time: Some(Duration::from_secs(15)),
            processes: ProcessLimit::Max(10),
            memory_kib: Some(512 * 1024),
            ..Default::default()
        };

        for compile_command in &language.compile {
            let result = self.run(
                compile_command,
                language,
                &source_name,
                output_name,
                true,
                &compile_limits,
            )?;

            if !result.status.success() {
                return Err(format!("compilation failed: {}", result.status).into());
            }
        }

        let problem = self.get_problem_from_path(problem)?;
        println!("extracted problem data: \n{problem:?}");

        let runtime_limits = Limits {
            time: Some(Duration::from_secs(1)),
            wall_time: Some(Duration::from_secs(3)),
            processes: ProcessLimit::Max(10),
            memory_kib: Some(256 * 1024),
            ..Default::default()
        };

        let result = self.run(
            &language.run,
            language,
            &source_name,
            output_name,
            false,
            &runtime_limits,
        )?;

        // TODO: rewrite nix vm tests to check returned metadata struct
        // instead of checking if judge-worker exited successfully
        if !result.status.success() {
            return Err(format!("execution failed: {}", result.status).into());
        }

        let metadata = result.meta;
        println!("metadata results from running submission:\n{metadata:?}");

        Ok(metadata)
    }

    fn cleanup(&mut self) {
        match self.isolate().arg("--cleanup").arg("--cg").status() {
            Ok(status) if !status.success() => {
                eprintln!("failed to clean up isolate box {}: {status}", self.box_id);
            }
            Err(error) => {
                eprintln!("failed to clean up isolate box {}: {error}", self.box_id);
            }
            _ => {}
        }
    }
}

impl Drop for IsolateBox {
    fn drop(&mut self) {
        self.cleanup();
    }
}
